const dictionaries: Record<Locale, Dict> = { es, en }

type LocaleContextValue = {
  locale: Locale
  setLocale: (locale: Locale) => void
  t: (key: string) => string
  toggleLocale: () => void
}

const LocaleContext = createContext<LocaleContextValue | null>(null)

export function LocaleProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>(() => {
    const stored = localStorage.getItem('ledgerai-locale')
    return stored === 'en' || stored === 'es' ? stored : 'es'
  })

  const persist = useCallback((next: Locale) => {
    setLocale(next)
    localStorage.setItem('ledgerai-locale', next)
  }, [])

  const t = useCallback(
    (key: string) => dictionaries[locale][key] ?? dictionaries.en[key] ?? key,
    [locale],
  )

  const toggleLocale = useCallback(() => {
    persist(locale === 'es' ? 'en' : 'es')
  }, [locale, persist])

  const value = useMemo(
    () => ({ locale, setLocale: persist, t, toggleLocale }),
    [locale, persist, t, toggleLocale],
  )

  return <LocaleContext.Provider value={value}>{children}</LocaleContext.Provider>
}

export function useLocale() {
  const ctx = useContext(LocaleContext)
  if (!ctx) throw new Error('useLocale must be used within LocaleProvider')
  return ctx
}
